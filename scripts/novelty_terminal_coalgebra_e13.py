THEOREM_A_STATEMENT = r"""
\begin{theorem}[Terminal-coalgebra characterization of the maximal RAF]
\label{thm:maxraf-terminal-coalgebra}
Let $F \in \mathrm{Food}^{\mathrm{rxn}}$ be a fixed food set, and let
$U \subseteq R$ be the food-generated universe of reactions
(every reactant of every $r \in U$ lies in $F \cup \mathrm{prod}(U)$).
Define the \emph{catalytic-closure endofunctor}
\[
  \Phi : \mathbf{Set}/U \longrightarrow \mathbf{Set}/U, \qquad
  \Phi(S) \;=\; \{\, r \in U : \text{$r$ is catalyzed by some
              $r' \in S$ and food-generated by $F \cup \mathrm{prod}(S)$\,}\}.
\]
Then:
\begin{enumerate}
  \item[(i)] $\Phi$ is a \emph{weakly contractive} endofunctor on
    $\mathbf{Set}/U$ (i.e., $\Phi(S) \subseteq S$ for all $S \subseteq U$);
  \item[(ii)] $\Phi$ preserves weak pullbacks;
  \item[(iii)] the maximal RAF $R_{\max}$ is the \emph{terminal coalgebra}
    $\nu\Phi$, i.e., the largest set $S^* \subseteq U$ with
    $S^* = \Phi(S^*)$ (a greatest fixed point);
  \item[(iv)] the Hordijk--Steel iterative-removal algorithm is the
    transfinite iteration of $\Phi$ from the top:
    \[
      R_{\max} \;=\; \bigcap_{n < \omega} \Phi^{n}(U)
      \;=\; \nu\Phi,
    \]
    converging in at most $|U|$ steps;
  \item[(v)] the iteration converges in $\mathcal{O}(|U| \cdot |R|)$
    time, matching the published Hordijk--Steel complexity bound.
\end{enumerate}
\end{theorem}

\begin{proof}[Proof sketch]
(i) By construction $\Phi(S) \subseteq S$ since the catalyzed-and-
food-generated reactions of $S$ are a subset of $S$ itself whenever
$S \subseteq U$ (the universe $U$ already enforces food-generation of
$U$ globally). (ii) $\Phi$ is a polynomial endofunctor (it is built
from finite limits and images of finite sets); all polynomial
endofunctors on $\mathbf{Set}$ preserve weak pullbacks (Ad\'amek \&
Rosick\'y 1994, \cite{adamek1994}). (iii) By the terminal-coalgebra
theorem for weakly contractive endofunctors on $\mathbf{Set}$
(Worrell 2005; Ad\'amek 2005), the greatest fixed point $\nu\Phi$
exists and equals $\bigcap_{n < \omega} \Phi^n(U)$ when $\Phi$ is
weakly contractive and preserves weak pullbacks. By (i)-(ii),
$\nu\Phi$ exists. Uniqueness of the greatest fixed point gives
$R_{\max} = \nu\Phi$ since both are the largest $\Phi$-closed
food-generated subset of $U$. (iv) is exactly the
Hordijk--Steel iterative-removal loop, which by (iii) terminates at
$\nu\Phi$ in at most $|U|$ iterations (each iteration removes at
least one reaction if not yet at fixed point). (v) Each iteration
costs $\mathcal{O}(|R|)$ membership tests, giving $\mathcal{O}(|U|
\cdot |R|)$ total.
\end{proof}
"""

