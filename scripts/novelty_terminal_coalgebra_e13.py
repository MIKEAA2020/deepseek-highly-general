THEOREM_B_STATEMENT = r"""
\begin{theorem}[Canonical functorial realization of the seven-optic composite]
\label{thm:seven-optic-functorial}
Let $\mathcal{C}$ be a monoidal category with finite limits and let
$\Per(\mathcal{C})$ be the category of \emph{periodic typed systems}:
objects are pairs $(X, f)$ with $X \in \mathrm{Ob}(\mathcal{C})$ and
$f : X \to X$ with $f^{n_X} = \mathrm{id}_X$ for some minimal period
$n_X \geq 1$; morphisms $h : (X,f) \to (Y,g)$ are $\mathcal{C}$-maps
$h : X \to Y$ with $h \circ f = g \circ h$ (period-equivariant maps).
Let $\OO_1, \ldots, \OO_7$ be the seven optics of
Construction~\ref{con:seven}, each realized as an optic in
$\Optic(\mathcal{C})$, and let $T = \OO_7 \circ \cdots \circ \OO_1$
be the composite endo-optic.

Then:
\begin{enumerate}
  \item[(i)] \textbf{Existence:} There is a canonical functor
    $\mathcal{R} : \Per(\mathcal{C}) \to \Optic(\mathcal{C})$
    factoring the composite $T$, i.e., for each $(X, f) \in \Per(\mathcal{C})$,
    $\mathcal{R}(X, f) = T|_{X}$, and the realization commutes with
    period-equivariant morphisms in the sense that the diagram
    \[
      \begin{tikzcd}[ampersand replacement=\&]
        (X, f) \ar[r, "h"] \ar[d, "\mathcal{R}"'] \&
        (Y, g) \ar[d, "\mathcal{R}"] \\
        T|_{X} \ar[r, "T(h)"'] \& T|_{Y}
      \end{tikzcd}
    \]
    commutes up to a 2-cell in the bicategory of optics.
  \item[(ii)] \textbf{Uniqueness (up to monoidal natural isomorphism):}
    Any other functor $\mathcal{R}' : \Per(\mathcal{C}) \to
    \Optic(\mathcal{C})$ satisfying the SAVGS-typing constraint
    (i.e., factoring the same $T = \OO_7 \circ \cdots \circ \OO_1$
    and respecting the seven-stage stratification) is monoidally
    naturally isomorphic to $\mathcal{R}$.
\end{enumerate}
\end{theorem}

\begin{proof}[Proof sketch]
(i) The existence half uses the standard construction of an optic
from a pair of forward/residual maps; here, the forward maps of
$\OO_1, \ldots, \OO_7$ are the SAVGS strata transitions, and the
residuals are inherited by the optic composition law (Riley 2018
\cite{riley2018optics}). The periodicity $f^{n_X} = \mathrm{id}$
ensures the realized map $T|_X : X \to X$ is also periodic of period
dividing $n_X$, so $\Per(\mathcal{C})$ is closed under $T$. (ii) The
uniqueness half follows from a parametricity argument
(Strachey--Reynolds) restricted to \emph{typed polynomial optics}: a
natural transformation $\alpha : \mathcal{R}' \Rightarrow \mathcal{R}$
is constructed by parametricity of the optic decomposition table
(see Riley 2023 \cite{riley2023} for the free-cornering calculus),
and the SAVGS typing constraint forces $\alpha$ to be monoidal. Full
proof requires the language of profunctorial optical polymorphism
(Riley 2019); the manuscript restricts to the set-level case here.
\end{proof}

\begin{remark}
\label{rem:e13-upgrade2-position}
Theorem~\ref{thm:maxraf-terminal-coalgebra} converts the manuscript's
filtered-colimit RAF construction (Construction~16.1) into a
\emph{terminal-coalgebra} result, connecting RAF theory to the
coinductive machinery used actively in applied-category-theory
(Hedges 2024). Theorem~\ref{thm:seven-optic-functorial} partially
closes the open problem declared in Remark~7.8 of the manuscript
(funct orial semantics of $T$ on a typed-system category) by
identifying the natural domain $\Per(\mathcal{C})$.
\end{remark}
"""

