def is_food_generated(reaction, foods, current_set):
    """A reaction is food-generated iff every reactant is in foods ∪ prod(current_set)."""
    reactants = reaction[1]
    available = set(foods)
    for cr in current_set:
        available |= cr[2]  # products of each current reaction
    return reactants.issubset(available)

def is_catalyzed(reaction, current_set):
    """A reaction is catalyzed iff at least one of its catalysts is in the products of current_set."""
    catalysts = reaction[3]
    if not catalysts:
        return True  # no catalyst required
    available_cat = set()
    for cr in current_set:
        available_cat |= cr[2]
    return bool(catalysts & available_cat)

# Adámek's iteration: start from full universe U; iteratively apply Φ
def phi(S, foods, reactions):
    """Catalytic-closure endofunctor: Φ(S) = { r ∈ U : catalyzed AND food-generated by S }."""
    return [r for r in reactions
            if is_catalyzed(r, S) and is_food_generated(r, foods, S)]

# Hordijk-Steel iterative-removal algorithm
def hordijk_steel(foods, reactions):
    """Iteratively remove uncatalyzed and non-food-generated reactions."""
    S = list(reactions)
    while True:
        S_new = [r for r in S
                 if is_catalyzed(r, S) and is_food_generated(r, foods, S)]
        if len(S_new) == len(S):
            return S
        S = S_new

# Terminal-coalgebra (Adámek) iteration
def adamek_terminal_coalgebra(foods, reactions):
    """Iterate Φ from the top: S_{n+1} = Φ(S_n), starting from S_0 = full universe."""
    S = list(reactions)
    iterations = [list(S)]
    while True:
        S_new = phi(S, foods, reactions)
        iterations.append(list(S_new))
        if len(S_new) == len(S):
            return S, iterations
        S = S_new

