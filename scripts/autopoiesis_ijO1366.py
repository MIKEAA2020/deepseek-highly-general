out_dir = "/home/z/my-project/download"
os.makedirs(out_dir, exist_ok=True)

with open(f"{out_dir}/autopoiesis_ijO1366.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["metabolite_id", "metabolite_name", "n_producing_reactions",
                "n_consuming_reactions", "baseline_prod_flux",
                "knockout_prod_flux", "knockout_biomass",
                "recovery_prod_flux", "recovery_biomass",
                "knockout_success", "recover_success",
                "causally_internal", "verdict"])
    for r in records:
        w.writerow([r["metabolite_id"], r["metabolite_name"],
                    r["n_producing_reactions"], r["n_consuming_reactions"],
                    r["baseline_prod_flux"], r["knockout_prod_flux"],
                    r["knockout_biomass"], r["recovery_prod_flux"],
                    r["recovery_biomass"], r["knockout_success"],
                    r["recover_success"], r["causally_internal"], r["verdict"]])

