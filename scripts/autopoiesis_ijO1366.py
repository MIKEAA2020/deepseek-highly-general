"""
Task 2: Extend the autopoiesis closure test (Definition def:autopoiesis of
the manuscript) to the FULL BiGG iJO1366 model of E. coli metabolism
(Orth et al. 2011; 1805 metabolites, 2583 reactions).

CONTEXT (manuscript):
  - The autopoiesis closure test was previously operationalized on a SMALL
    10-species, 10-reaction E. coli core-metabolic subnetwork (Network B in
    Section sec:autopoiesis-real-networks). The verdict was 0/10 causally
    internal (HOMEOSTATIC), because the enzymes catalyzing metabolic
    reactions are not modeled as species in the metabolic-only submodel.
  - The user now requests extending the test to the FULL BiGG iJO1366 model
    to confirm the homeostatic verdict at genome scale.

APPROACH:
  - Load iJO1366 via cobrapy (cobra.io.load_model). This gives 1805
    metabolites, 2583 reactions, of which 1805 - 7 = 1798 non-food
    metabolites (excluding typical food: glucose, O2, NH3, H2O, CO2, H+, Pi).
  - For each non-food metabolite m_j, run the closure test:
    (i)   set the reactions producing m_j to zero internal repair flux
          (knockout);
    (ii)  keep external food supply unchanged;
    (iii) simulate the FBA (Flux Balance Analysis) steady state with the
          producing reactions knocked out; observe whether m_j still has
          non-trivial flux balance (i.e., is regenerated by other reactions);
    (iv)  restore the producing reactions and run the recovery test.
  - FBA is the appropriate computational tool for genome-scale metabolism
    (the test cannot run a full dynamic simulation with Michaelis-Menten
    kinetics on 2583 reactions; FBA gives the steady-state flux distribution
    that maximizes biomass subject to constraints, and is the standard tool
    for genome-scale metabolic analysis).
  - DECISION: m_j is "causally internal" iff (a) the knockout sends its
    steady-state flux below the viability threshold (the metabolite is no
    longer produced at steady state), AND (b) the recovery test restores
    the producing reactions and the metabolite's flux recovers above the
    threshold.

  We use the biomass reaction (iJO1366 biomass objective) as the viability
  function V: the system is viable iff biomass flux > 0. The closure test
  per-component is then: does m_j's production flux remain non-trivial
  when its producing reactions are knocked out? If YES, then m_j is
  regenerated by alternative pathways (PLENTY of redundancy in genome-scale
  metabolism); if NO, then m_j's production is fragile.

  Note: the full 2583-reaction iJO1366 network has SUBSTANTIAL redundancy
  (multiple pathways producing most metabolites). So the test should reveal
  MANY causally internal components (in contrast to the small 10-species
  subnetwork). The test thus operationalizes the autopoiesis-vs-homeostasis
  distinction at genome scale.

  To keep the test tractable, we:
  - Exclude exchange, demand, and biomass reactions (focus on internal
    metabolic reactions).
  - Run the test on a random sample of 50 non-food metabolites (uniformly
    drawn) plus the 10 metabolites from Network B (G6P, FBP, PEP, PYR,
    AcCoA, CIT, AKG, SUC, MAL, OAA) for direct comparison.
  - For each, run FBA knockout + recovery test.
"""
import numpy as np
import os, csv, json

# Load iJO1366 via cobrapy
from cobra.io import load_model
from cobra.flux_analysis import single_reaction_deletion, single_gene_deletion

print("=" * 78)
print("TASK 2: AUTOPOIESIS CLOSURE TEST ON FULL BiGG iJO1366 MODEL")
print("       (Orth et al. 2011; 1805 metabolites, 2583 reactions)")
print("=" * 78)
print()

print("Loading iJO1366 model via cobrapy...")
model = load_model("iJO1366")
print(f"  Loaded: {len(model.metabolites)} metabolites, {len(model.reactions)} reactions")
print(f"  Compartments: {sorted(model.compartments.keys())}")
print()

# Identify food (external) species: exchange reactions typically start with "EX_"
exchange_rxns = [r for r in model.reactions if r.id.startswith("EX_")]
print(f"  Exchange reactions (food sources): {len(exchange_rxns)}")
food_metabolites = set()
for r in exchange_rxns:
    for met in r.metabolites:
        if r.metabolites[met] < 0:  # metabolite is taken up (consumed) by exchange
            food_metabolites.add(met.id)
print(f"  Food metabolites (taken up by exchange reactions): {len(food_metabolites)}")
print(f"  (these are the externally supplied 'food' species F subset M)")
print()

# Identify biomass reaction (the viability function V)
biomass_rxns = [r for r in model.reactions if "biomass" in r.id.lower() or "BIOMASS" in r.id]
print(f"  Biomass reactions (viability function V): {[r.id for r in biomass_rxns]}")
if biomass_rxns:
    biomass_rxn = biomass_rxns[0]
    print(f"  Using biomass reaction: {biomass_rxn.id} as viability function V")
print()

# Identify non-food metabolites (in the cytosolic compartment c)
cytosolic_mets = [m for m in model.metabolites if m.compartment == 'c'
                  and m.id not in food_metabolites]
print(f"  Cytosolic non-food metabolites (M_ess): {len(cytosolic_mets)}")
print()

# For each non-food metabolite, find the reactions that PRODUCE it
# (positive stoichiometric coefficient)
def producing_reactions(met):
    """Return list of (reaction_id, stoich) of reactions that produce this metabolite."""
    producers = []
    for r in met.reactions:
        coef = r.get_coefficient(met.id) if hasattr(r, 'get_coefficient') else r.metabolites.get(met, 0)
        if coef > 0:
            producers.append((r.id, coef))
    return producers

# For each non-food metabolite, find the reactions that CONSUME it
def consuming_reactions(met):
    consumers = []
    for r in met.reactions:
        coef = r.get_coefficient(met.id) if hasattr(r, 'get_coefficient') else r.metabolites.get(met, 0)
        if coef < 0:
            consumers.append((r.id, abs(coef)))
    return consumers

# Pick test set: 10 metabolites from Network B (for direct comparison) + 50 random
np.random.seed(20260830)
network_B_mets = ["g6p_c", "fdp_c", "pep_c", "pyr_c", "accoa_c",
                  "cit_c", "akg_c", "succ_c", "mal__L_c", "oaa_c"]
# Map Network B names to iJO1366 IDs
name_map = {
    "G6P": "g6p_c", "FBP": "fdp_c", "PEP": "pep_c", "PYR": "pyr_c",
    "AcCoA": "accoa_c", "CIT": "cit_c", "AKG": "akg_c", "SUC": "succ_c",
    "MAL": "mal__L_c", "OAA": "oaa_c"
}
test_metabolite_ids = []
for name, mid in name_map.items():
    if mid in [m.id for m in cytosolic_mets]:
        test_metabolite_ids.append(mid)

# Add 40 random non-food metabolites (different from the 10 above)
all_non_food_ids = [m.id for m in cytosolic_mets]
random_pool = [m for m in all_non_food_ids if m not in test_metabolite_ids]
random_sample = np.random.choice(random_pool, size=min(40, len(random_pool)), replace=False).tolist()
test_metabolite_ids = test_metabolite_ids + random_sample
print(f"Test set: {len(test_metabolite_ids)} non-food metabolites")
print(f"  - {len(name_map)} from Network B (for direct comparison with Section 17):")
for name, mid in name_map.items():
    print(f"      {name} -> {mid}")
print(f"  - {len(random_sample)} random cytosolic metabolites (uniform draw from {len(random_pool)})")
print()

# Closure test: for each test metabolite m_j, knockout the reactions producing m_j
# (set their flux bounds to 0), run FBA, and observe:
#   - Was m_j's production flux knocked out? (knockout test)
#   - Does the biomass objective remain positive? (system viability)
#   - After restoring the knocked-out reactions, does m_j's production flux recover? (recovery)

def run_fba(m):
    """Run FBA on model m, return (status, biomass_flux, metabolite_fluxes)."""
    sol = m.optimize()
    if sol.status == 'optimal':
        return sol.objective_value, sol.fluxes
    else:
        return None, None

# Baseline FBA
print("Running baseline FBA on full iJO1366...")
baseline_obj, baseline_fluxes = run_fba(model)
print(f"  Baseline biomass flux: {baseline_obj:.6f}")
print()

# Viability threshold: 10% of baseline biomass (system is "viable" if biomass > 0.1 * baseline)
viability_threshold = 0.1 * baseline_obj
flux_threshold = 1e-6  # metabolite production flux above this is "non-trivial"
print(f"Viability threshold (biomass > 0.1 * baseline): {viability_threshold:.6f}")
print(f"Flux threshold (production > 1e-6): {flux_threshold}")
print()

# Run the closure test
print("Running closure test (knockout producing reactions, observe, restore)...")
print(f"  {'metabolite':>14}  {'n_prod':>6}  {'baseline_prod_flux':>20}  "
      f"{'knockout_prod_flux':>20}  {'recovery_prod_flux':>20}  {'verdict':>14}")
print("  " + "-" * 110)

records = []
for m_id in test_metabolite_ids:
    met = model.metabolites.get_by_id(m_id)
    producers = producing_reactions(met)
    consumers = consuming_reactions(met)
    n_prod = len(producers)

    # Baseline production flux: sum of (flux * stoich) over producing reactions
    baseline_prod = 0.0
    if baseline_fluxes is not None:
        for rid, coef in producers:
            rflux = baseline_fluxes.get(rid, 0.0) if hasattr(baseline_fluxes, 'get') else 0.0
            baseline_prod += coef * max(rflux, 0.0)  # only forward flux produces

    # Knockout: set producing reactions' lower and upper bounds to 0
    with model:
        for rid, _ in producers:
            if rid in model.reactions:
                r = model.reactions.get_by_id(rid)
                r.lower_bound = 0
                r.upper_bound = 0
        knock_obj, knock_fluxes = run_fba(model)
    knock_prod = 0.0
    if knock_fluxes is not None:
        for rid, coef in producers:
            rflux = knock_fluxes.get(rid, 0.0) if hasattr(knock_fluxes, 'get') else 0.0
            knock_prod += coef * max(rflux, 0.0)

    # Recovery: restore and re-run FBA
    rec_obj, rec_fluxes = run_fba(model)
    rec_prod = 0.0
    if rec_fluxes is not None:
        for rid, coef in producers:
            rflux = rec_fluxes.get(rid, 0.0) if hasattr(rec_fluxes, 'get') else 0.0
            rec_prod += coef * max(rflux, 0.0)

    # Verdict: causally internal iff
    # (a) baseline production > threshold (m_j is being produced)
    # (b) knockout production < threshold (m_j is knocked out successfully)
    # (c) recovery production > threshold (m_j recovers)
    knock_success = baseline_prod > flux_threshold and knock_prod < flux_threshold
    recover_success = rec_prod > flux_threshold
    causally_internal = knock_success and recover_success
    verdict = "AUTOPOIETIC" if causally_internal else "HOMEOSTATIC"

    records.append({
        "metabolite_id": m_id,
        "metabolite_name": met.name,
        "n_producing_reactions": n_prod,
        "n_consuming_reactions": len(consumers),
        "baseline_prod_flux": baseline_prod,
        "knockout_prod_flux": knock_prod,
        "knockout_biomass": knock_obj if knock_obj is not None else 0.0,
        "recovery_prod_flux": rec_prod,
        "recovery_biomass": rec_obj if rec_obj is not None else 0.0,
        "knockout_success": knock_success,
        "recover_success": recover_success,
        "causally_internal": causally_internal,
        "verdict": verdict,
    })

    short_id = m_id[:14]
    print(f"  {short_id:>14}  {n_prod:>6}  {baseline_prod:>20.6f}  "
          f"{knock_prod:>20.6f}  {rec_prod:>20.6f}  {verdict:>14}")

print()
n_autopoietic = sum(1 for r in records if r["causally_internal"])
n_total = len(records)
n_homeostatic = n_total - n_autopoietic
print(f"VERDICT (test set of {n_total} metabolites from full iJO1366):")
print(f"  AUTOPOIETIC (causally internal): {n_autopoietic}/{n_total}")
print(f"  HOMEOSTATIC (not causally internal): {n_homeostatic}/{n_total}")
print(f"  Fraction causally internal: {n_autopoietic / n_total:.2%}")
print()

# Stratify by number of producing reactions
print("Stratified by number of producing reactions:")
from collections import Counter
n_prod_counter = Counter(r["n_producing_reactions"] for r in records)
for n_prod in sorted(n_prod_counter.keys()):
    subset = [r for r in records if r["n_producing_reactions"] == n_prod]
    n_sub = len(subset)
    n_auto_sub = sum(1 for r in subset if r["causally_internal"])
    print(f"  n_producing_reactions = {n_prod}: {n_sub} metabolites, "
          f"{n_auto_sub}/{n_sub} causally internal")
print()

# Compare to Network B
print("Comparison to Network B (10-species core-metabolic subnetwork):")
print("  Network B: 0/10 causally internal (HOMEOSTATIC)")
print(f"  Full iJO1366 (test set of {n_total}): {n_autopoietic}/{n_total} causally internal")
network_B_in_ijO = [r for r in records if r["metabolite_id"] in name_map.values()]
n_B_auto = sum(1 for r in network_B_in_ijO if r["causally_internal"])
print(f"  Of the 10 Network B metabolites tested at genome scale: "
      f"{n_B_auto}/{len(network_B_in_ijO)} causally internal")
print()

